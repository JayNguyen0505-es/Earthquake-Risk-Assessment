package vn.vast.vasteq.station;

import java.util.Map;
import io.quarkus.test.junit.QuarkusTest;
import io.quarkus.narayana.jta.QuarkusTransaction;
import jakarta.inject.Inject;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.*;
import vn.vast.vasteq.user.*;
import static io.restassured.RestAssured.given;
import static org.hamcrest.Matchers.*;

@QuarkusTest
class StationResourceTest {
    static final String ROOT = "/api/v1/station";
    static final String PASSWORD = "station-test-password";
    @Inject StationRepository stations;
    @Inject UserRepository users;
    @Inject PasswordHasher passwords;
    @Inject EntityManager entityManager;

    @BeforeEach void clean() {
        QuarkusTransaction.requiringNew().run(() -> {
            // Production channels are defined by deployment SQL, not this station API.
            entityManager.createNativeQuery("CREATE TABLE IF NOT EXISTS channels (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, station_id BIGINT NOT NULL, FOREIGN KEY (station_id) REFERENCES stations(id))").executeUpdate();
            entityManager.createNativeQuery("DELETE FROM channels").executeUpdate();
            stations.deleteAll(); users.deleteAll();
        });
    }

    String token(User.Role role) {
        String email = role.name() + "@station.example.com";
        QuarkusTransaction.requiringNew().run(() -> {
            User user = new User(); user.email = email; user.displayName = role.name();
            user.role = role; user.passwordHash = passwords.hash(PASSWORD); users.persist(user);
        });
        return given().contentType("application/json").body(Map.of("email", email, "password", PASSWORD))
            .post("/api/v1/user/login").then().statusCode(200).extract().path("accessToken");
    }
    long create(String admin, String code, Map<String, Object> extra) {
        var input = new java.util.HashMap<String, Object>(extra);
        input.put("networkCode", "VN"); input.put("stationCode", code);
        Number id = given().auth().oauth2(admin).contentType("application/json").body(input)
            .post(ROOT).then().statusCode(201).header("Location", containsString(ROOT + "/"))
            .body("createdAt", notNullValue()).body("updatedAt", notNullValue()).extract().path("id");
        return id.longValue();
    }

    @Test void authenticatedReadsAndAdminOnlyWrites() {
        String admin = token(User.Role.admin);
        long id = create(admin, "4001", Map.of("name", "Test station"));
        given().get(ROOT).then().statusCode(401);
        given().get(ROOT + "/" + id).then().statusCode(401);
        for (User.Role role : new User.Role[]{User.Role.user, User.Role.guest}) {
            String reader = token(role);
            given().auth().oauth2(reader).get(ROOT).then().statusCode(200).body("total", is(1));
            given().auth().oauth2(reader).get(ROOT + "/" + id).then().statusCode(200).body("stationCode", is("4001"));
            given().auth().oauth2(reader).contentType("application/json").body(Map.of("networkCode", "VN", "stationCode", "4002"))
                .post(ROOT).then().statusCode(403);
            given().auth().oauth2(reader).contentType("application/json").body(Map.of("name", "Forbidden"))
                .patch(ROOT + "/" + id).then().statusCode(403);
            given().auth().oauth2(reader).delete(ROOT + "/" + id).then().statusCode(403);
        }
    }

    @Test void patchPreservesOmittedFieldsAndClearsExplicitNulls() {
        String admin = token(User.Role.admin);
        long id = create(admin, "4001", Map.of("name", "Original", "province", "Sơn La", "instrumentSerial", "00123"));
        given().auth().oauth2(admin).get(ROOT + "/" + id).then().body("latitude", nullValue()).body("longitude", nullValue());
        given().auth().oauth2(admin).contentType("application/json").body(Map.of("latitude", 21.123456, "longitude", 103.123456, "coordinateCrs", "EPSG:4326"))
            .patch(ROOT + "/" + id).then().statusCode(200).body("name", is("Original")).body("instrumentSerial", is("00123"));
        given().auth().oauth2(admin).contentType("application/json").body("{\"name\":null,\"latitude\":null,\"longitude\":null}")
            .patch(ROOT + "/" + id).then().statusCode(200).body("name", nullValue()).body("latitude", nullValue())
            .body("longitude", nullValue()).body("province", is("Sơn La"));
        given().auth().oauth2(admin).delete(ROOT + "/" + id).then().statusCode(204);
        given().auth().oauth2(admin).get(ROOT + "/" + id).then().statusCode(404);
    }

    @Test void filtersSearchAndPagination() {
        String admin = token(User.Role.admin);
        create(admin, "4001", Map.of("name", "Sơn La 100%", "province", "Sơn La", "city", "City A", "latitude", 21, "longitude", 103));
        create(admin, "4002", Map.of("name", "Other station", "province", "Điện Biên"));
        given().auth().oauth2(admin).get(ROOT + "?limit=1&offset=1").then().statusCode(200)
            .body("total", is(2)).body("items.size()", is(1)).body("items[0].stationCode", is("4002"));
        given().auth().oauth2(admin).queryParam("networkCode", "VN").queryParam("stationCode", "4001")
            .queryParam("province", "Sơn La").queryParam("city", "City A").get(ROOT).then().statusCode(200).body("total", is(1));
        given().auth().oauth2(admin).queryParam("search", "sơn la").queryParam("hasCoordinates", true)
            .get(ROOT).then().statusCode(200).body("total", is(1));
        given().auth().oauth2(admin).queryParam("search", "%").get(ROOT).then().statusCode(200).body("total", is(1));
        given().auth().oauth2(admin).get(ROOT + "?hasCoordinates=false").then().statusCode(200).body("items[0].stationCode", is("4002"));
        given().auth().oauth2(admin).get(ROOT + "?offset=100").then().statusCode(200).body("items.size()", is(0)).body("total", is(2));
        for (String query : new String[]{"limit=101", "limit=0", "offset=-1", "offset=2147483647&limit=2", "hasCoordinates=invalid"})
            given().auth().oauth2(admin).get(ROOT + "?" + query).then().statusCode(400);
    }

    @Test void invalidInputAndDuplicateCodes() {
        String admin = token(User.Role.admin);
        long first = create(admin, "4001", Map.of());
        long second = create(admin, "4002", Map.of());
        given().auth().oauth2(admin).contentType("application/json").body(Map.of("networkCode", "VN", "stationCode", "4001"))
            .post(ROOT).then().statusCode(409).body("code", is("station_exists"));
        given().auth().oauth2(admin).contentType("application/json").body(Map.of("stationCode", "4001"))
            .patch(ROOT + "/" + second).then().statusCode(409);
        given().auth().oauth2(admin).get(ROOT + "/" + second).then().body("stationCode", is("4002"));
        for (String patch : new String[]{"{}", "[]", "null", "{\"id\":7}", "{\"networkCode\":null}",
                "{\"stationCode\":\"123456\"}", "{\"networkCode\":\"越\"}", "{\"latitude\":21}",
                "{\"latitude\":91,\"longitude\":103}", "{\"latitude\":21,\"longitude\":181}",
                "{\"latitude\":21.1234567,\"longitude\":103}", "{\"elevationM\":\"invalid\"}"})
            given().auth().oauth2(admin).contentType("application/json").body(patch).patch(ROOT + "/" + first).then().statusCode(400);
        given().auth().oauth2(admin).contentType("application/json").body("{\"networkCode\":\"VN\",\"stationCode\":\"4003\",\"latitude\":21}")
            .post(ROOT).then().statusCode(400);
        given().auth().oauth2(admin).contentType("application/json").body("{}").post(ROOT).then().statusCode(400);
        given().auth().oauth2(admin).contentType("application/json").body("{\"networkCode\":\"VN\",\"stationCode\":\"4003\",\"unknown\":1}")
            .post(ROOT).then().statusCode(400);
        given().auth().oauth2(admin).get(ROOT + "/999999").then().statusCode(404);
        given().auth().oauth2(admin).contentType("application/json").body(Map.of("name", "Changed"))
            .patch(ROOT + "/999999").then().statusCode(404);
        given().auth().oauth2(admin).delete(ROOT + "/999999").then().statusCode(404);
    }

    @Test void linkedChannelsPreventDeletion() {
        String admin = token(User.Role.admin);
        long id = create(admin, "4001", Map.of());
        QuarkusTransaction.requiringNew().run(() -> entityManager.createNativeQuery("INSERT INTO channels(station_id) VALUES (:id)")
            .setParameter("id", id).executeUpdate());
        given().auth().oauth2(admin).delete(ROOT + "/" + id).then().statusCode(409).body("code", is("station_in_use"));
        given().auth().oauth2(admin).get(ROOT + "/" + id).then().statusCode(200);
    }

    @Test void accountStateIsCheckedBeyondTokenClaims() {
        String admin = token(User.Role.admin);
        long id = create(admin, "4001", Map.of());
        QuarkusTransaction.requiringNew().run(() -> {
            User user = users.byEmail("admin@station.example.com"); user.role = User.Role.user;
        });
        given().auth().oauth2(admin).contentType("application/json").body(Map.of("name", "Forbidden"))
            .patch(ROOT + "/" + id).then().statusCode(403);
        QuarkusTransaction.requiringNew().run(() -> users.byEmail("admin@station.example.com").enabled = false);
        given().auth().oauth2(admin).get(ROOT).then().statusCode(401);
        given().auth().oauth2(admin).get(ROOT + "/" + id).then().statusCode(401);
    }
}
